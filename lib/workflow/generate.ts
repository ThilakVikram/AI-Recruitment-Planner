import "server-only";
import { ApiError } from "@/lib/api/errors";
import { clip, formatPreviousContext, loadRoleContext, STAGE_CONTEXT_DEPENDENCIES } from "@/lib/ai/context";
import { mapWithConcurrency } from "@/lib/ai/run";
import { runKickoffChain } from "@/lib/ai/chains/kickoff";
import { runMarketResearchChain } from "@/lib/ai/chains/market-research";
import { runSourcingStrategyChain } from "@/lib/ai/chains/sourcing";
import { runOutreachChain } from "@/lib/ai/chains/outreach";
import { runRecruiterScreeningChain } from "@/lib/ai/chains/recruiter-screening";
import { runFinalDecisionChain } from "@/lib/ai/chains/final-decision";
import { getCandidatesWithLatestCv } from "@/lib/db/candidates";
import { findSourcingProfileByName } from "@/lib/db/sourcing";
import { saveStageOutput } from "@/lib/db/stages";

const CV_PROMPT_MAX_CHARS = 40_000;

type GenerateArgs = { roleId: string; stageNumber: number; input: string; candidateIds?: string[] };

function bullets(value: unknown): string {
  return Array.isArray(value) && value.length ? value.map((v) => `- ${String(v)}`).join("\n") : "None recorded.";
}

/** Runs the AI chain for a stage, with only the relevant previous-stage context, and persists the result. */
export async function generateStage({ roleId, stageNumber, input, candidateIds }: GenerateArgs) {
  const ctx = await loadRoleContext(roleId, stageNumber);
  const previousContext = formatPreviousContext(ctx.stages, STAGE_CONTEXT_DEPENDENCIES[stageNumber] ?? []);

  switch (stageNumber) {
    case 1: {
      if (input.trim().length < 20) throw new ApiError(400, "Please enter the kick-off meeting notes first.");
      const { markdown, data } = await runKickoffChain({ roleName: ctx.roleName, input });
      return saveStageOutput(roleId, 1, { input, output: markdown, outputData: data });
    }
    case 2: {
      if (!ctx.stages.get(1)?.output) throw new ApiError(400, "Generate the Stage 1 kick-off output first.");
      const output = await runMarketResearchChain({ roleName: ctx.roleName, previousContext, input });
      return saveStageOutput(roleId, 2, { input, output });
    }
    case 3: {
      if (!ctx.stages.get(1)?.output) throw new ApiError(400, "Generate the Stage 1 kick-off output first.");
      const output = await runSourcingStrategyChain({ roleName: ctx.roleName, previousContext, input });
      return saveStageOutput(roleId, 3, { input, output });
    }
    case 4:
      throw new ApiError(400, "Stage 4 is generated by uploading and scoring CVs.");
    case 5:
    case 6:
    case 7:
      return generateCandidateStage(stageNumber, roleId, input, candidateIds ?? [], ctx);
    default:
      throw new ApiError(400, "Unknown stage.");
  }
}

async function generateCandidateStage(
  stageNumber: 5 | 6 | 7 | number,
  roleId: string,
  input: string,
  candidateIds: string[],
  ctx: Awaited<ReturnType<typeof loadRoleContext>>,
) {
  if (!candidateIds.length) throw new ApiError(400, "Select at least one candidate.");
  if (stageNumber === 6 && candidateIds.length !== 1) throw new ApiError(400, "Select exactly one candidate for screening.");
  if (stageNumber === 6 && input.trim().length < 20) throw new ApiError(400, "Please enter the screening interview notes.");
  if (stageNumber === 5 && candidateIds.length > 10) throw new ApiError(400, "Select at most 10 candidates at a time.");

  // Role-scoped lookup: ids from another role are silently ignored, then rejected below.
  const candidates = await getCandidatesWithLatestCv(roleId, candidateIds);
  if (candidates.length !== new Set(candidateIds).size) throw new ApiError(404, "One or more candidates were not found in this role.");

  const sections = await mapWithConcurrency(candidates, 3, async (c) => {
    const cvText = clip(c.cvs[0]?.extractedText ?? "No CV on file.", CV_PROMPT_MAX_CHARS);
    const score = c.score === null ? "Not scored" : `${c.score}/100`;
    let body: string;
    if (stageNumber === 5) {
      const profile = await findSourcingProfileByName(roleId, c.normalizedName);
      const sourcingInfo = profile
        ? `Platform: ${profile.platform}\n${clip(profile.profileText, 8_000)}`
        : "No sourcing profile on file for this candidate.";
      body = await runOutreachChain({
        roleName: ctx.roleName,
        jobDescription: ctx.jobDescription,
        scorecard: ctx.scorecard,
        candidateName: c.name,
        score,
        summary: c.summary ?? "Not available.",
        strengths: bullets(c.strengths),
        sourcingInfo,
        cvText,
        input,
      });
    } else if (stageNumber === 6) {
      body = await runRecruiterScreeningChain({
        roleName: ctx.roleName,
        scorecard: ctx.scorecard,
        candidateName: c.name,
        score,
        category: c.category ?? "Not scored",
        summary: c.summary ?? "Not available.",
        cvText,
        input,
      });
    } else {
      body = await runFinalDecisionChain({
        roleName: ctx.roleName,
        candidateName: c.name,
        strengths: bullets(c.strengths),
        gaps: bullets(c.gaps),
        input,
      });
    }
    return `## ${c.name}\n\n${body}`;
  });

  return saveStageOutput(roleId, stageNumber, {
    input,
    inputData: { candidateIds: candidates.map((c) => c.id) },
    output: sections.join("\n\n---\n\n"),
  });
}
